"""
Automatic Meeting Ingestion for Zoom and Google Meet.
Ingests meeting recordings, cloud webhook payloads, and transcript exports from Zoom & Google Meet,
and automatically routes them into the existing Sales Meeting Agent pipeline.

Supports:
1. Zoom Cloud Recording Webhooks (event: 'recording.completed') & Zoom Recording Links
2. Google Meet Webhook Events / Space Artifacts & Google Meet Transcripts (VTT / text exports)
3. Direct audio streams (.m4a, .mp3, .wav) and VTT/SRT transcript cleanup
"""

import re
import json
from pathlib import Path
from typing import Dict, Any, Optional, Union

from agent.sales_meeting_agent import SalesMeetingAgent, AgentResult


def clean_vtt_transcript(vtt_text: str) -> str:
    """
    Cleans WebVTT / SRT subtitle & transcript files generated by Zoom or Google Meet.
    Removes WEBVTT headers, cue identifiers, and timestamps (e.g. 00:00:01.000 --> 00:00:05.000),
    preserving clean dialogue and speaker names.
    """
    lines = vtt_text.splitlines()
    cleaned_lines = []
    timestamp_pattern = re.compile(r"^\s*(\d{1,2}:)?\d{2}:\d{2}[\.,]\d{3}\s*-->\s*(\d{1,2}:)?\d{2}:\d{2}[\.,]\d{3}")
    vtt_header_pattern = re.compile(r"^(WEBVTT|NOTE|STYLE|REGION)(\s.*)?$", re.IGNORECASE)

    for line in lines:
        stripped = line.strip()
        if not stripped:
            continue
        if vtt_header_pattern.match(stripped):
            continue
        if timestamp_pattern.match(stripped):
            continue
        if stripped.isdigit():
            # SubRip sequence number
            continue
        cleaned_lines.append(stripped)

    # Join and normalize dialogue
    return "\n".join(cleaned_lines)


def parse_zoom_payload(payload: Dict[str, Any]) -> Dict[str, Any]:
    """
    Parses a Zoom Cloud Recording webhook payload ('recording.completed') or Zoom API payload.
    """
    obj = payload.get("payload", {}).get("object", {}) if "payload" in payload else payload
    meeting_id = obj.get("id") or obj.get("uuid") or payload.get("meeting_id", "zoom-meeting")
    topic = obj.get("topic") or payload.get("topic", "Zoom Sales Meeting")
    duration = obj.get("duration") or payload.get("duration", 30)
    host_email = obj.get("host_email") or payload.get("host_email", "")

    # Look for transcript text, VTT file, or audio recording
    recording_files = obj.get("recording_files", []) or payload.get("recording_files", [])
    transcript_text = payload.get("transcript", "")
    audio_source = None

    for rf in recording_files:
        file_type = (rf.get("file_type") or rf.get("recording_type") or "").upper()
        if "TRANSCRIPT" in file_type or rf.get("file_extension") == "VTT":
            if rf.get("transcript_content"):
                transcript_text = clean_vtt_transcript(rf.get("transcript_content"))
        elif file_type in ("AUDIO", "M4A", "MP3", "WAV") or rf.get("file_extension") in ("m4a", "mp3", "wav"):
            audio_source = rf.get("download_url") or rf.get("file_path") or rf.get("bytes")

    if not transcript_text and payload.get("transcript_content"):
        transcript_text = clean_vtt_transcript(payload.get("transcript_content"))

    return {
        "platform": "zoom",
        "meeting_id": str(meeting_id),
        "topic": topic,
        "duration_minutes": duration,
        "host_email": host_email,
        "transcript": transcript_text,
        "audio_source": audio_source,
    }


def parse_google_meet_payload(payload: Dict[str, Any]) -> Dict[str, Any]:
    """
    Parses a Google Meet webhook payload, Space artifact event, or Google Meet export.
    """
    space = payload.get("space", {}) if "space" in payload else payload
    meeting_code = space.get("meeting_code") or payload.get("meeting_code") or payload.get("conference_id", "meet-call")
    title = space.get("title") or payload.get("title") or payload.get("topic", "Google Meet Session")
    host_email = payload.get("host_email") or payload.get("organizer_email", "")
    duration = payload.get("duration_minutes") or payload.get("duration", 30)

    transcript_text = payload.get("transcript") or payload.get("transcript_text") or ""
    if not transcript_text and payload.get("transcript_content"):
        transcript_text = clean_vtt_transcript(payload.get("transcript_content"))
    elif transcript_text and ("WEBVTT" in transcript_text or "-->" in transcript_text):
        transcript_text = clean_vtt_transcript(transcript_text)

    audio_source = payload.get("audio_source") or payload.get("recording_url") or payload.get("file_path")

    return {
        "platform": "google_meet",
        "meeting_id": str(meeting_code),
        "topic": title,
        "duration_minutes": duration,
        "host_email": host_email,
        "transcript": transcript_text,
        "audio_source": audio_source,
    }


class MeetingIngestionClient:
    """
    Unified Ingestion Client for Zoom and Google Meet meetings.
    Automatically obtains recording/transcript and invokes the existing Sales Meeting Agent.
    """

    def __init__(self, agent: Optional[SalesMeetingAgent] = None):
        self.agent = agent or SalesMeetingAgent()

    def ingest(
        self,
        meeting_input: Union[Dict[str, Any], str, Path],
        platform: str = "auto",
        auto_confirm: bool = True
    ) -> Dict[str, Any]:
        """
        Ingests a Zoom or Google Meet meeting payload, recording, or transcript,
        and automatically runs it through the existing Sales Meeting Agent pipeline.
        """
        metadata = {}
        target_source = None

        # 1. Inspect and parse dictionary payload
        if isinstance(meeting_input, dict):
            # Auto-detect provider
            is_zoom = (
                platform.lower() == "zoom" or
                "zoom" in str(meeting_input).lower() or
                "recording_files" in meeting_input or
                meeting_input.get("event") == "recording.completed"
            )
            if is_zoom:
                metadata = parse_zoom_payload(meeting_input)
            else:
                metadata = parse_google_meet_payload(meeting_input)

            if metadata.get("audio_source"):
                target_source = metadata["audio_source"]
            elif metadata.get("transcript"):
                target_source = metadata["transcript"]
            elif meeting_input.get("raw_text"):
                target_source = meeting_input["raw_text"]

        # 2. Inspect string input (URL, file path, or VTT transcript)
        elif isinstance(meeting_input, (str, Path)):
            text_str = str(meeting_input).strip()
            # If string is a JSON payload
            if text_str.startswith("{") and text_str.endswith("}"):
                try:
                    payload_dict = json.loads(text_str)
                    return self.ingest(payload_dict, platform=platform, auto_confirm=auto_confirm)
                except Exception:
                    pass

            # Detect platform from URL or content
            lower_str = text_str.lower()
            if "zoom.us" in lower_str or "zoom" in lower_str:
                detected_platform = "zoom"
            elif "meet.google.com" in lower_str or "google" in lower_str:
                detected_platform = "google_meet"
            else:
                detected_platform = "zoom" if platform.lower() == "zoom" else "google_meet"

            metadata = {
                "platform": detected_platform,
                "meeting_id": "auto-ingested-meeting",
                "topic": "Sales Discovery Meeting",
                "duration_minutes": 30,
            }

            # Check if file path
            path = Path(text_str)
            if path.exists() and path.is_file():
                ext = path.suffix.lower()
                if ext in (".vtt", ".srt", ".txt"):
                    content = path.read_text(encoding="utf-8", errors="replace")
                    target_source = clean_vtt_transcript(content)
                else:
                    target_source = path
            elif "WEBVTT" in text_str or "-->" in text_str:
                target_source = clean_vtt_transcript(text_str)
            else:
                target_source = text_str

        if not target_source:
            raise ValueError("No valid audio source or transcript found in meeting ingestion payload.")

        # 3. Route automatically into existing Sales Meeting Agent pipeline
        agent_result = self.agent.run_end_to_end_pipeline(target_source, auto_confirm=auto_confirm)

        return {
            "success": True,
            "platform": metadata.get("platform", "auto"),
            "meeting_id": metadata.get("meeting_id"),
            "topic": metadata.get("topic"),
            "duration_minutes": metadata.get("duration_minutes"),
            "host_email": metadata.get("host_email"),
            "agent_result": agent_result,
        }


def ingest_meeting(
    meeting_input: Union[Dict[str, Any], str, Path],
    platform: str = "auto",
    agent: Optional[SalesMeetingAgent] = None,
    auto_confirm: bool = True
) -> Dict[str, Any]:
    """
    Convenience function to ingest Zoom or Google Meet meetings into the Sales Meeting Agent.
    """
    client = MeetingIngestionClient(agent=agent)
    return client.ingest(meeting_input, platform=platform, auto_confirm=auto_confirm)
